-- Lowercase, without Slovenian's and its neighbours' diacritics, as Kotlin's fold has these letters
CREATE FUNCTION fold_sl(said TEXT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE AS
$$
SELECT translate(lower(said), 'čšžćđ', 'cszcd')
$$;

-- The region of a place, by its name and its address, either may be null: ONLINE for one that's online (as isOnline in
-- Events.kt, a name without an address), else what places finds in them, first by rank, then the longest; null when
-- nothing does. STABLE, not IMMUTABLE, as it reads places: so not for a generated column.
CREATE FUNCTION region_of(place TEXT, address TEXT) RETURNS TEXT
    LANGUAGE sql STABLE AS
$$
SELECT CASE
           WHEN said.folded = '' THEN NULL
           WHEN btrim(coalesce(address, '')) = ''
               AND said.folded ~ '\m(online|on-line|splet\w*|virtual\w*|zoom|teams|youtube|discord|webinar\w*)\M' THEN 'ONLINE'
           ELSE (SELECT p.region
                 FROM places p
                 WHERE said.folded ~ ('\m(' || p.pattern || ')\M')
                 ORDER BY p.rank, length(p.pattern) DESC, p.pattern
                 LIMIT 1)
           END
FROM (SELECT fold_sl(btrim(concat_ws(' ', place, address))) AS folded) said
$$;

