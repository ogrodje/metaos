-- Regions (Regions.kt, OG-71): where an event is, for the Events page's filter. Slovenia's 12 statistical regions, as
-- they are since 2015 (https://sl.wikipedia.org/wiki/Statistične_regije_Slovenije), and ONLINE and ABROAD. An event's
-- is told from where it says it is, else it's its organisation's, told from its venue; the team sets either by hand.

-- What tells a region in a place's name or address: a pattern (a regular expression of whole words, in fold_sl's
-- letters) and the region it means. Looked for by rank, then the longest: abroad (0), a postcode (1), a place's name
-- (2), a region's (3). Reference data, so without an audit trigger.
--
-- Where it's from, on 19 Nov 2026:
--  - the 212 municipalities by region: the article above, "Občine po statističnih regijah";
--  - the 478 postcodes with their posts: Pošta Slovenije's "Seznam poštnih številk za naslavljanje"
--    (https://www.posta.si/zasebno-site/Documents/Seznami/Seznam poštnih številk za naslavljanje.pdf). A post's region
--    is its municipality's: 191 posts are named as one, 6 are parts of a city (Ljubljana - Šentvid), 186 are
--    settlements Wikidata has in one municipality (P131), and 95 were placed by hand, as their names are several
--    settlements' or Wikidata's was another's (Kamnica is Maribor's, not Dol pri Ljubljani's);
--  - names: the municipalities, but those that are words or names too (Grad, Tabor, Mirna, Videm, Ig, Benedikt,
--    Lenart, Muta, Kozje, Dobje, Sveta Ana, Sveti Tomaž), posts of more than a word that are one settlement's, a few
--    towns that are neither (Portorož, Solkan), and the larger towns as they're said after "v" (v Novi Gorici).
CREATE TABLE places
(
    rank    SMALLINT NOT NULL,
    pattern TEXT     NOT NULL,
    region  TEXT     NOT NULL,
    -- What it is, as it's written: the post's name, the municipality's, the region's
    name    TEXT     NOT NULL,
    PRIMARY KEY (rank, pattern)
);

